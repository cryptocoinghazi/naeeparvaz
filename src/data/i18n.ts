export const routeSegments = {
  home: "",
  about: "about",
  vision: "vision-mission",
  contact: "contact",
  videos: "videos",
  news: "news",
  disclaimer: "disclaimer",
} as const;

export type RouteKey = keyof typeof routeSegments;

export function isLocale(value: string | undefined): value is Locale {
  return value === "en" || value === "hi";
}

export function localePath(locale: Locale, route: RouteKey, hash = ""): string {
  const segment = routeSegments[route];
  return `/${locale}/${segment ? `${segment}/` : ""}${hash}`;
}

export function switchLocalePath(pathname: string, locale: Locale): string {
  const segments = pathname.split("/").filter(Boolean);
  if (segments[0] === "en" || segments[0] === "hi") segments[0] = locale;
  else segments.unshift(locale);
  return `/${segments.join("/")}/`;
}

